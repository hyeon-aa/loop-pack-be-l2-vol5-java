#!/usr/bin/env python3
"""Summarize k6 records. This script sends no HTTP requests."""
import argparse
from collections import Counter
import json
import math
from pathlib import Path


def percentile(values, rank):
    values = sorted(values)
    return values[max(0, math.ceil(len(values) * rank) - 1)] if values else 0


def summarize(calls, rate, seconds, begin_ms=0):
    within = sum(r['startOffsetMs'] < begin_ms + seconds * 1000 for r in calls)
    times = [r['elapsedMs'] for r in calls]
    return {
        'count': len(calls), 'targetRate': rate, 'startsWithinWindow': within,
        'actualStartsPerSecond': within / seconds,
        'httpStatuses': dict(Counter(str(r['httpStatus']) for r in calls)),
        'paymentStatuses': dict(Counter(r['paymentStatus'] for r in calls if r.get('paymentStatus'))),
        'checkedTrue': sum(r.get('checked') is True for r in calls),
        'checkedFalse': sum(r.get('checked') is False for r in calls),
        'p50Ms': percentile(times, .5), 'p99Ms': percentile(times, .99),
        'maxStartLagMs': max((r['startLagMs'] for r in calls), default=0),
        'transportErrors': sum('transportError' in r for r in calls),
    }


def main():
    parser = argparse.ArgumentParser()
    for name in ['config', 'raw', 'k6-summary', 'output']:
        parser.add_argument('--' + name, type=Path, required=True)
    args = parser.parse_args()
    config = json.loads(args.config.read_text())
    native = json.loads(args.k6_summary.read_text())
    records = []
    for line in args.raw.read_text().splitlines():
        if not line.startswith('{'):
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError:
            continue
        if record.get('kind') in ('call', 'phase', 'origin'):
            records.append(record)
    calls = [r for r in records if r['kind'] == 'call']
    changes = sorted([r for r in records if r['kind'] == 'phase'], key=lambda r: r['plannedOffsetMs'])
    origins = [r['startedEpochMillis'] for r in records if r['kind'] == 'origin']
    if len(origins) != 1:
        raise ValueError('Missing k6 time origin')
    seconds = config['seconds']
    planned = {}
    schedule = {}
    for group, base_rate in config['rates'].items():
        points = []
        for second in range(seconds):
            rate = next((w['rate'] for w in config.get('rateWindows', {}).get(group, [])
                         if w['startSeconds'] <= second < w['endSeconds']), base_rate)
            points.extend((second + within / rate) * 1000 for within in range(rate))
        schedule[group] = points
        planned[group] = len(points)
    phases = []
    for index, phase in enumerate(changes):
        begin = phase['appliedOffsetMs']
        end = changes[index + 1]['appliedOffsetMs'] if index + 1 < len(changes) else seconds * 1000
        selected = [r for r in calls if begin <= r['startOffsetMs'] < end]
        for r in selected:
            r['phase'] = phase['name']
            r['crossesPhaseBoundary'] = r['startOffsetMs'] + r['elapsedMs'] >= end
        planned_end = changes[index + 1]['plannedOffsetMs'] if index + 1 < len(changes) else seconds * 1000
        duration = max(.001, (end - begin) / 1000)
        phase_rates = {g: sum(phase['plannedOffsetMs'] <= t < planned_end for t in points)
                          / max(.001, (planned_end - phase['plannedOffsetMs']) / 1000)
                       for g, points in schedule.items()}
        phases.append({'name': phase['name'], 'beginMs': begin, 'endMs': end, 'byRequestStart': True,
                       'crossingCalls': sum(r['crossesPhaseBoundary'] for r in selected),
                       'summary': {g: summarize([r for r in selected if r['group'] == g], phase_rates[g], duration, begin)
                                   for g in config['rates']}})
    events = []
    for r in calls:
        events.extend([(r['startOffsetMs'], 1), (r['startOffsetMs'] + max(.001, r['elapsedMs']), -1)])
    active = peak = 0
    for _, delta in sorted(events):
        active += delta
        peak = max(peak, active)
    dropped = native.get('metrics', {}).get('dropped_iterations', {}).get('values', {}).get('count', 0)
    summary = {g: summarize([r for r in calls if r['group'] == g], planned[g] / seconds, seconds)
               for g in config['rates']}
    output = {
        'scope': 'Actual API HTTP generated by Grafana k6; Python only summarizes records',
        'generator': 'k6', 'seconds': seconds, 'startedEpochMillis': origins[0],
        'scheduledCounts': planned, 'peakClientInFlight': peak, 'droppedIterations': dropped,
        'boundaryIterationsIgnored': native.get('metrics', {}).get('api_boundary_iterations_ignored', {}).get('values', {}).get('count', 0),
        'summary': summary, 'phaseChanges': changes, 'phases': phases, 'calls': calls, 'k6Summary': native,
    }
    args.output.write_text(json.dumps(output, ensure_ascii=False, indent=2) + '\n')
    print(json.dumps({'generator': 'k6', 'droppedIterations': dropped, 'summary': summary}, ensure_ascii=False))
    if dropped != 0 or any(summary[g]['count'] != planned[g] for g in planned):
        raise SystemExit('k6 did not start all scheduled API iterations')


if __name__ == '__main__':
    main()
